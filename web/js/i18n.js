export const getLang = () => current;
export function setLang(lang) {
  if (!LANGS[lang]) return;
  current = lang;
  try { localStorage.setItem(KEY, lang); } catch { /* 저장 불가 */ }
  document.documentElement.lang = lang;
  window.dispatchEvent(new Event('rl:lang'));
}

"""인증 협력자의 경계. 실제 공급사 대신 테스트 대역으로 오류·만료를 검증한다."""
from dataclasses import dataclass, field
from typing import Protocol, ContextManager

@dataclass(frozen=True)
class User:
    id: str
    email: str
    confirmed: bool = True

    def public(self):
        return {"id": self.id, "email": self.email, "email_confirmed": self.confirmed}

@dataclass
class Tokens:
    user: User
    access: str = field(repr=False)
    refresh: str = field(repr=False)
    expires_in: float

@dataclass
class Session:
    tokens: Tokens = field(repr=False)
    created: float
    seen: float
    access_until: float
    purpose: str = "login"

class Provider(Protocol):
    def signup(self, email: str, password: str): ...
    def login(self, email: str, password: str) -> Tokens: ...
    def verify(self, token_hash: str, kind: str) -> Tokens: ...
    def refresh(self, token: str) -> Tokens: ...
    def user(self, token: str) -> User: ...
    def recover(self, email: str): ...
    def password(self, token: str, password: str): ...
    def logout(self, token: str, scope: str = "local"): ...

class Store(Protocol):
    def prune(self, before: float): ...
    def put(self, session_id: str, session: Session): ...
    def get(self, session_id: str) -> Session | None: ...
    def drop(self, session_id: str): ...
    def drop_user(self, user_id: str): ...
    def locked(self, session_id: str) -> ContextManager: ...
    def claim(self, kind: str, resource_id: str, user_id: str): ...
    def owner(self, kind: str, resource_id: str) -> str | None: ...
